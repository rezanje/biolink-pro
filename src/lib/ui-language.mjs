export function translate(message, locale, variables = {}) {
    const index = uiLanguage(locale) === 'id' ? 0 : uiLanguage(locale) === 'zh-CN' ? 1 : -1
    const template = index < 0 ? message : UI_MESSAGES[message]?.[index] || message
    return template.replace(/\{(\w+)\}/g, (_, key) => String(variables[key] ?? `{${key}}`))
}
